

public class OOPSBannerApp {

    public static void main(String[] args) {

        // Each line constructed using String.join()

        System.out.println(String.join("",
                "  *****  ", "  *****  ", "  ****** ", "  ****** "));

        System.out.println(String.join("",
                " **   ** ", " **   ** ", " **   ** ", " **      "));

        System.out.println(String.join("",
                " **   ** ", " **   ** ", " **   ** ", " **      "));

        System.out.println(String.join("",
                " **   ** ", " **   ** ", " ******  ", "  *****  "));

        System.out.println(String.join("",
                " **   ** ", " **   ** ", " **      ", "       **"));

        System.out.println(String.join("",
                " **   ** ", " **   ** ", " **      ", " **    **"));

        System.out.println(String.join("",
                "  *****  ", "  *****  ", " **      ", "  ****** "));
    }
}